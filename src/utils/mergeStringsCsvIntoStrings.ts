import lodashFpMerge from "lodash/fp/merge.js";

import isObject from "./isObject.js";
import stringsCsvToValuesByFlatKeys from "./stringsCsvToValuesByFlatKeys.js";
import valuesByFlatKeysToNestedObject from "./valuesByFlatKeysToNestedObject.js";

/**
 * Get flat dot-separated keys of an object’s string values.
 */
const getStringValueFlatKeys = (
  obj: Record<string, unknown>,
  prefix = "",
): Array<string> =>
  Object.entries(obj).flatMap(([key, value]) => {
    const flatKey = prefix ? `${prefix}.${key}` : key;

    return isObject(value)
      ? getStringValueFlatKeys(value, flatKey)
      : typeof value === "string"
        ? [flatKey]
        : [];
  });

/**
 * Merge translations from strings CSV text content (as generated by
 * `stringsJsonToCsv`) into an existing strings object.
 *
 * Only the CSV’s "Key" and "Translation" columns are used. Rows with a
 * translation of "---" are skipped.
 *
 * @returns `mergedStrings`: New strings object (`currentStrings` isn’t
 * mutated). `unknownFlatKeys`: Keys of CSV translations that weren’t already
 * strings in `currentStrings` (e.g. typos or keys removed since the CSV was
 * generated). These are still merged.
 *
 * @public
 */
const mergeStringsCsvIntoStrings = ({
  currentStrings,
  stringsCsvTextContent,
}: {
  currentStrings: Record<string, unknown>;
  stringsCsvTextContent: string;
}): {
  mergedStrings: Record<string, unknown>;
  unknownFlatKeys: Array<string>;
} => {
  const valuesByFlatKeys = stringsCsvToValuesByFlatKeys(stringsCsvTextContent);

  const currentFlatKeys = new Set(getStringValueFlatKeys(currentStrings));

  return {
    mergedStrings: lodashFpMerge(
      currentStrings,
      valuesByFlatKeysToNestedObject(valuesByFlatKeys),
    ),
    unknownFlatKeys: Object.keys(valuesByFlatKeys).filter(
      (flatKey) => !currentFlatKeys.has(flatKey),
    ),
  };
};

export default mergeStringsCsvIntoStrings;
