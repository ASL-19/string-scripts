import isObject from "./isObject.js";

/**
 * Replace newlines in description with single space and trim.
 */
const normalizeDescription = (description: unknown): string =>
  typeof description === "string"
    ? description.replace(/\n+/g, " ").trim()
    : "";

/**
 * Resolve local JSON Schema `$ref` (e.g. `#/definitions/PageStrings`) against
 * the schema root. Returns `undefined` if it doesn’t resolve.
 */
const resolveRef = ({
  ref,
  schemaJson,
}: {
  ref: string;
  schemaJson: Record<string, unknown>;
}): unknown => {
  if (!ref.startsWith("#")) {
    throw new Error(
      `Unsupported $ref "${ref}" (only local references are supported)`,
    );
  }

  // JSON Pointer segments are URI-encoded in the fragment (ts-json-schema-
  // generator encodes generic type names, e.g. `Record%3Cstring%2Cstring%3E`)
  // and escape "~" and "/" as "~0" and "~1"
  return ref
    .slice(1)
    .split("/")
    .slice(1)
    .map((segment) =>
      decodeURIComponent(segment).replaceAll("~1", "/").replaceAll("~0", "~"),
    )
    .reduce<unknown>(
      (acc, segment) => (isObject(acc) ? acc[segment] : undefined),
      schemaJson,
    );
};

/**
 * Follow a schema’s chain of `$ref`s to the schema it refers to.
 *
 * @returns The resolved schema and the `$ref`s followed to reach it
 */
const dereference = ({
  schema,
  schemaJson,
}: {
  schema: unknown;
  schemaJson: Record<string, unknown>;
}): { refs: Array<string>; schema: unknown } => {
  const refs: Array<string> = [];
  let currentSchema = schema;

  while (isObject(currentSchema) && typeof currentSchema.$ref === "string") {
    const ref = currentSchema.$ref;

    if (refs.includes(ref)) {
      throw new Error(`Circular $ref "${ref}"`);
    }

    refs.push(ref);
    currentSchema = resolveRef({ ref, schemaJson });

    if (currentSchema === undefined) {
      throw new Error(`Couldn’t resolve $ref "${ref}"`);
    }
  }

  return { refs, schema: currentSchema };
};

/**
 * Recursively get descriptions of an object type schema’s `properties` (and
 * their properties), by flat dot-separated key.
 *
 * Array types have no `properties`, so their items’ descriptions aren’t
 * included.
 */
const getPropertyDescriptionEntries = ({
  ancestorRefs,
  prefix,
  schema,
  schemaJson,
}: {
  /** `$ref`s of the types being parsed (to stop at recursive types) */
  ancestorRefs: ReadonlySet<string>;
  prefix: string;
  /** Dereferenced object type schema */
  schema: unknown;
  schemaJson: Record<string, unknown>;
}): Array<[string, string]> =>
  isObject(schema) && isObject(schema.properties)
    ? Object.entries(schema.properties).flatMap(([key, propertySchema]) => {
        const flatKey = prefix ? `${prefix}.${key}` : key;

        const { refs, schema: resolvedPropertySchema } = dereference({
          schema: propertySchema,
          schemaJson,
        });

        // A property’s own description (a docstring on the property) takes
        // precedence over its type’s (a docstring on a named type)
        const description =
          normalizeDescription(
            isObject(propertySchema) ? propertySchema.description : undefined,
          ) ||
          normalizeDescription(
            isObject(resolvedPropertySchema)
              ? resolvedPropertySchema.description
              : undefined,
          );

        const isRecursive = refs.some((ref) => ancestorRefs.has(ref));

        return [
          [flatKey, description],
          ...(isRecursive
            ? []
            : getPropertyDescriptionEntries({
                ancestorRefs: new Set([...ancestorRefs, ...refs]),
                prefix: flatKey,
                schema: resolvedPropertySchema,
                schemaJson,
              })),
        ];
      })
    : [];

const invalidRootErrorMessage =
  "Schema root (the type its $ref refers to, or definitions.Strings if it doesn’t have one) must be an object type with properties";

/**
 * Given the content of a strings JSON Schema (as generated by
 * ts-json-schema-generator), returns each string’s (and each object of
 * strings’) docstring description by flat dot-separated key.
 *
 * The root type is the one the schema’s root `$ref` refers to (or
 * `definitions.Strings` if it doesn’t have one), and `$ref`s are followed
 * wherever they appear. Array items’ descriptions aren’t included.
 *
 * @example
 *
 * ```ts
 * getSchemaDescriptionsByFlatKey(schemaJson);
 * // Map { "page" => "Page.", "page.title" => "Page title." }
 * ```
 */
const getSchemaDescriptionsByFlatKey = (
  schemaJson: unknown,
): Map<string, string> => {
  if (!isObject(schemaJson)) {
    throw new Error(invalidRootErrorMessage);
  }

  const { refs, schema: rootSchema } = dereference({
    schema: {
      $ref:
        typeof schemaJson.$ref === "string"
          ? schemaJson.$ref
          : "#/definitions/Strings",
    },
    schemaJson,
  });

  if (!isObject(rootSchema) || !isObject(rootSchema.properties)) {
    throw new Error(invalidRootErrorMessage);
  }

  return new Map(
    getPropertyDescriptionEntries({
      ancestorRefs: new Set(refs),
      prefix: "",
      schema: rootSchema,
      schemaJson,
    }),
  );
};

export default getSchemaDescriptionsByFlatKey;
