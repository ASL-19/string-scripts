import isObject from "./isObject.js";

/**
 * Replace newlines in description with single space and trim.
 */
const normalizeDescription = (description: unknown): string =>
  typeof description === "string"
    ? description.replace(/\n+/g, " ").trim()
    : "";

/**
 * Recursively convert JSON Schema `properties` object to object of
 * `$description`s (mutates `outerKeyObj`).
 */
const parseProperties = (
  properties: Record<string, unknown>,
  outerKeyObj: Record<string, unknown>,
): void => {
  for (const [innerKey, innerValue] of Object.entries(properties)) {
    const innerKeyObj: Record<string, unknown> = {
      $description: isObject(innerValue)
        ? normalizeDescription(innerValue.description)
        : "",
    };

    // eslint-disable-next-line no-param-reassign
    outerKeyObj[innerKey] = innerKeyObj;

    if (isObject(innerValue) && isObject(innerValue.properties)) {
      parseProperties(innerValue.properties, innerKeyObj);
    }
  }
};

/**
 * Given the content of a strings JSON Schema (as generated by
 * ts-json-schema-generator from a `Strings` type whose top-level properties
 * have types named `${Key}Strings`), returns an object of its nested
 * properties with $description keys containing each string’s docstring
 * description.
 *
 * @returns Object in the form:
 *
 * ```js
 * {
 *   TopLevelKey1: {
 *     $description: "TopLevelKey1 description",
 *     nestedKey1: {
 *       $description: "nestedKey1 description"
 *       deeplyNestedKey1: {
 *         $description: "deeplyNestedKey1 description"
 *       }
 *     }
 *     nestedKey2: {
 *       $description: "nestedKey2 description"
 *     }
 *   }
 * }
 * ```
 */
const getNestedStringsObjectDescriptions = (
  schemaJson: unknown,
): Record<string, unknown> => {
  if (
    !isObject(schemaJson) ||
    !isObject(schemaJson.definitions) ||
    !isObject(schemaJson.definitions.Strings) ||
    !isObject(schemaJson.definitions.Strings.properties)
  ) {
    throw new Error(
      "Schema must contain a definitions.Strings object with properties",
    );
  }

  const definitions = schemaJson.definitions;
  const stringsProperties = schemaJson.definitions.Strings.properties;

  return Object.entries(stringsProperties).reduce<Record<string, unknown>>(
    (acc, [topLevelStringsKey, topLevelStringsProperty]) => {
      if (topLevelStringsKey === "$schema") {
        return acc;
      }

      const topLevelStringsTypeName =
        topLevelStringsKey.charAt(0).toUpperCase() +
        topLevelStringsKey.slice(1) +
        "Strings";

      const topLevelStringsType = definitions[topLevelStringsTypeName];

      if (
        !isObject(topLevelStringsType) ||
        !isObject(topLevelStringsType.properties)
      ) {
        return acc;
      }

      const topLevelKeyObj: Record<string, unknown> = {
        $description: isObject(topLevelStringsProperty)
          ? normalizeDescription(topLevelStringsProperty.description)
          : "",
      };

      parseProperties(topLevelStringsType.properties, topLevelKeyObj);

      return { ...acc, [topLevelStringsKey]: topLevelKeyObj };
    },
    {},
  );
};

export default getNestedStringsObjectDescriptions;
